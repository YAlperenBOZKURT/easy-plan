const dictionaries: Record<AppLocale, Record<TranslationKey, string>> = { tr, en };

export function detectLocale(): AppLocale {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === 'tr' || saved === 'en') return saved;
  return navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function translate(locale: AppLocale, key: TranslationKey, values?: TranslationValues): string {
  let message = dictionaries[locale][key] ?? tr[key];
  for (const [name, value] of Object.entries(values ?? {})) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

interface I18nValue {
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
}

const defaultValue: I18nValue = {
  locale: 'tr',
  setLocale: () => undefined,
  t: (key, values) => translate('tr', key, values),
};

const I18nContext = createContext<I18nValue>(defaultValue);

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: AppLocale }) {
  const [locale, setLocale] = useState<AppLocale>(() => initialLocale ?? detectLocale());

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => translate(locale, key, values),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = (): I18nValue => useContext(I18nContext);
